using DimensionalQuantities.Roslyn.Discovery;
using DimensionalQuantities.Roslyn.Generators;
using DimensionalQuantities.Build.Units;
using DimensionalQuantities.Units;

if (args.Length != 1)
{
	throw new ArgumentException("Expected the generated source path.");
}

List<UnitConversionSpec> quantities = [];
foreach (KeyValuePair<DimensionalQuantities.Dimensions.Dimension, UnitDefinition[]> entry in EngineeringCatalogue.Entries)
{
	if (!EngineeringQuantityAliases.Entries.TryGetValue(entry.Key, out string[]? aliases) ||
		!aliases.SequenceEqual(entry.Value.Select(unit => unit.QuantityName)))
	{
		throw new InvalidOperationException($"Metric catalogue aliases differ from core for {entry.Key}.");
	}

	quantities.Add(new(entry.Value[0].QuantityName, QuantityTypeNameFormatter.Format(entry.Key),
		[.. entry.Value], true));
}

string source = "// <auto-generated />\n" + UnitConversionEmitter.Emit(quantities,
	"DimensionalQuantities.Extensions.Metric", "public");
string path = Path.GetFullPath(args[0]);
Directory.CreateDirectory(Path.GetDirectoryName(path)!);
if (!File.Exists(path) || File.ReadAllText(path) != source)
{
	File.WriteAllText(path, source);
}
