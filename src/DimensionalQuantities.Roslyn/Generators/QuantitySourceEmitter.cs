using DimensionalQuantities.Roslyn.Discovery;

namespace DimensionalQuantities.Roslyn.Generators;

internal static class QuantitySourceEmitter
{
	public static string Emit(IReadOnlyList<PlannedQuantity> quantities)
	{
		string aliases = string.Join("\n", quantities.SelectMany(quantity =>
			quantity.Aliases.Select(alias => $"global using {alias} = {QuantityTypeNameFormatter.Format(quantity.Dimension)};")));
		UnitConversionSpec[] conversions = quantities.Where(quantity => !quantity.Units.IsEmpty)
			.Select(quantity => new UnitConversionSpec(quantity.Name, quantity.Name, quantity.Units,
				quantity.IncludeNamedConversions)).ToArray();
		string extensions = UnitConversionSourceEmitter.Emit(conversions, "DimensionalQuantities.Generated", "internal");
		return $"""
			// <auto-generated />
			{aliases}
			global using DimensionalQuantities.Generated;

			{extensions}
			""";
	}
}
