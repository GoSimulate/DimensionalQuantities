using System.Text;
using DimensionalQuantities.Dimensions;
using DimensionalQuantities.Roslyn.Discovery;
using DimensionalQuantities.Units;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace DimensionalQuantities.Roslyn.Generators;

internal static class MetricConversionSourceEmitter
{
	public static void Register(IncrementalGeneratorInitializationContext context)
	{
		IncrementalValueProvider<bool> enabled = context.AnalyzerConfigOptionsProvider.Select(static (options, _) =>
			options.GlobalOptions.TryGetValue("build_property.GenerateMetricConversions", out string? value)
			&& string.Equals(value, "true", StringComparison.OrdinalIgnoreCase));
		context.RegisterSourceOutput(enabled, static (output, isEnabled) =>
		{
			if (isEnabled)
			{
				output.AddSource("MetricConversions.g.cs", SourceText.From(Emit(), Encoding.UTF8));
			}
		});
	}

	private static string Emit()
	{
		List<UnitConversionSpec> quantities = [];
		foreach (KeyValuePair<Dimension, UnitDefinition[]> entry in EngineeringCatalogue.Entries)
		{
			if (!EngineeringQuantityAliases.Entries.TryGetValue(entry.Key, out string[]? aliases) ||
				!aliases.SequenceEqual(entry.Value.Select(unit => unit.QuantityName)))
			{
				throw new InvalidOperationException($"Metric catalogue aliases differ from core for {entry.Key}.");
			}

			quantities.Add(new(entry.Value[0].QuantityName, QuantityTypeNameFormatter.Format(entry.Key),
				[.. entry.Value], true));
		}

		return "// <auto-generated />\n" + UnitConversionEmitter.Emit(quantities,
			"DimensionalQuantities.Extensions.Metric", "public");
	}
}
