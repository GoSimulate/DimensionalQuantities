using System.Globalization;
using System.Text;
using DimensionalQuantities.DimensionAnalysis;
using DimensionalQuantities.TypeSystem;
using DimensionalQuantities.Units;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace DimensionalQuantities.Roslyn.Generators;

[Generator]
public sealed class VoltageGenerator : IIncrementalGenerator
{
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		context.RegisterPostInitializationOutput(static output => output.AddSource("Voltage.g.cs", SourceText.From(GenerateSource(), Encoding.UTF8)));
	}

	private static string GenerateSource()
	{
		Dimension dimension = EngineeringCatalogue.Entries.Single(entry => entry.Value.Any(unit => unit.Name == "Voltage")).Key;
		string mechanicalName = DimensionNameGenerator.GetQuantityName(dimension);
		string quantityType = $"global::DimensionalQuantities.TypeSystem.Quantity<global::DimensionalQuantities.TypeSystem.Dimension<{string.Join(", ", GetExponentTypes(dimension).Select(FormatType))}>>";
		KeyValuePair<int, SiPrefix>[] prefixes = SiPrefixes.Entries.OrderByDescending(entry => entry.Key).ToArray();
		string prefixedFactories = string.Join("\n\t\t", prefixes
			.Select(entry => $"public static Voltage From{entry.Value.Name}Volts(double value) => Voltage.FromSiBaseUnit(value * 1e{entry.Key.ToString(CultureInfo.InvariantCulture)});"));
		string prefixedAccessors = string.Join("\n\t\t", prefixes
			.Select(entry => $"public double As{entry.Value.Name}Volts() => voltage.AsSiBaseUnit() / 1e{entry.Key.ToString(CultureInfo.InvariantCulture)};"));
		return $$"""
			// <auto-generated />
			global using Voltage = {{quantityType}};
			global using {{mechanicalName}} = {{quantityType}};
			global using DimensionalQuantities.Generated;

			namespace DimensionalQuantities.Generated;

			internal static class VoltageExtensions
			{
				extension(Voltage)
				{
					public static Voltage FromVolts(double value) => Voltage.FromSiBaseUnit(value);
					{{prefixedFactories}}
				}

				extension(Voltage voltage)
				{
					public double AsVolts() => voltage.AsSiBaseUnit();
					{{prefixedAccessors}}
				}
			}
			""";
	}

	private static Type[] GetExponentTypes(Dimension dimension) =>
	[
		TypeSystemNumberCodec.CreateType(dimension.Length),
		TypeSystemNumberCodec.CreateType(dimension.Mass),
		TypeSystemNumberCodec.CreateType(dimension.Time),
		TypeSystemNumberCodec.CreateType(dimension.ElectricCurrent),
		TypeSystemNumberCodec.CreateType(dimension.Temperature),
		TypeSystemNumberCodec.CreateType(dimension.AmountOfSubstance),
		TypeSystemNumberCodec.CreateType(dimension.LuminousIntensity)
	];

	private static string FormatType(Type type)
	{
		string name = $"global::{type.Namespace}.{type.Name.Split('`')[0]}";
		return type.IsConstructedGenericType ? $"{name}<{string.Join(", ", type.GetGenericArguments().Select(FormatType))}>" : name;
	}
}
