using System.Collections.Immutable;
using DimensionalQuantities.Units.Declarations;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace DimensionalQuantities.Roslyn.Generators;

internal static class UnitProviderGenerationCoordinator
{
	public static IncrementalValuesProvider<INamedTypeSymbol> FindProviders(IncrementalGeneratorInitializationContext context)
	{
		return context.SyntaxProvider.ForAttributeWithMetadataName(
			typeof(UnitProviderAttribute).FullName!,
			static (node, _) => node is TypeDeclarationSyntax,
			static (syntaxContext, _) => (INamedTypeSymbol)syntaxContext.TargetSymbol);
	}

	public static ImmutableArray<GeneratedSource> Generate(Compilation compilation, ImmutableArray<INamedTypeSymbol> providers,
		Action<Diagnostic> report)
	{
		ImmutableArray<GeneratedSource>.Builder sources = ImmutableArray.CreateBuilder<GeneratedSource>();
		HashSet<INamedTypeSymbol> seen = new(SymbolEqualityComparer.Default);
		foreach (INamedTypeSymbol provider in providers)
		{
			if (!seen.Add(provider))
			{
				continue;
			}

			IReadOnlyList<UnitConversionSpec> units = new UnitProviderReader(compilation).Read(provider, report);
			if (units.Count == 0)
			{
				continue;
			}

			try
			{
				string namespaceName = provider.ContainingNamespace.IsGlobalNamespace
					? string.Empty : provider.ContainingNamespace.ToDisplayString();
				string source = "// <auto-generated />\n" + UnitConversionSourceEmitter.Emit(units, namespaceName, "public",
					ClassNamePrefix(provider));
				string hint = provider.ToDisplayString() + ".g.cs";
				sources.Add(new(hint, source));
			}
			catch (InvalidOperationException exception)
			{
				report(Diagnostic.Create(GenerationDiagnostics.InvalidUnitProvider,
					provider.Locations.FirstOrDefault() ?? Location.None, exception.Message));
			}
		}

		return sources.ToImmutable();
	}

	private static string ClassNamePrefix(INamedTypeSymbol provider)
	{
		Stack<INamedTypeSymbol> types = new();
		for (INamedTypeSymbol? type = provider; type is not null; type = type.ContainingType)
		{
			types.Push(type);
		}

		return string.Concat(types.Select(type => $"P{type.Name.Length}_{type.Name}A{type.Arity}_"));
	}
}
