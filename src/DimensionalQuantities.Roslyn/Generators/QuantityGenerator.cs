using System.Globalization;
using System.Text;
using DimensionalQuantities.DimensionAnalysis;
using DimensionalQuantities.TypeSystem;
using DimensionalQuantities.Units;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace DimensionalQuantities.Roslyn.Generators;

[Generator]
public sealed class QuantityGenerator : IIncrementalGenerator
{
	public void Initialize(IncrementalGeneratorInitializationContext context)
	{
		context.RegisterPostInitializationOutput(static output => output.AddSource("Quantities.g.cs", SourceText.From(GenerateSource(), Encoding.UTF8)));
	}

	private static string GenerateSource()
	{
		StringBuilder aliases = new();
		StringBuilder extensions = new();
		KeyValuePair<int, SiPrefix>[] prefixes = SiPrefixes.Entries.OrderByDescending(entry => entry.Key).ToArray();
		Dimension[] baseDimensions =
		[
			new(Length: 1),
			new(Mass: 1),
			new(Time: 1),
			new(ElectricCurrent: 1),
			new(Temperature: 1),
			new(AmountOfSubstance: 1),
			new(LuminousIntensity: 1)
		];

		foreach (Dimension dimension in baseDimensions)
		{
			DimensionComponent component = dimension.GetComponents().Single();
			AppendQuantity(aliases, extensions, prefixes, dimension, component.Unit);
		}

		KeyValuePair<Dimension, UnitDefinition[]> voltage = EngineeringCatalogue.Entries.Single(entry => entry.Value.Any(unit => unit.QuantityName == "Voltage"));
		UnitDefinition voltageUnit = voltage.Value.Single(unit => unit.QuantityName == "Voltage");
		AppendQuantity(aliases, extensions, prefixes, voltage.Key, voltageUnit);

		return $$"""
			// <auto-generated />
			{{aliases}}global using DimensionalQuantities.Generated;

			namespace DimensionalQuantities.Generated;

			internal static class QuantityExtensions
			{
			{{extensions}}}
			""";
	}

	private static void AppendQuantity(StringBuilder aliases, StringBuilder extensions, KeyValuePair<int, SiPrefix>[] prefixes, Dimension dimension, UnitDefinition unit)
	{
		string quantityName = unit.QuantityName;
		string unitName = unit.PrefixableUnitNamePlural;
		int siBasePrefixExponent = unit.SiBasePrefixExponent;
		string mechanicalName = DimensionNameGenerator.GetQuantityName(dimension);
		string quantityType = $"global::DimensionalQuantities.TypeSystem.Quantity<global::DimensionalQuantities.TypeSystem.Dimension<{string.Join(", ", GetExponentTypes(dimension).Select(FormatType))}>>";
		aliases.Append("global using ").Append(quantityName).Append(" = ").Append(quantityType).AppendLine(";");
		if (mechanicalName != quantityName)
		{
			aliases.Append("global using ").Append(mechanicalName).Append(" = ").Append(quantityType).AppendLine(";");
		}

		extensions.Append("\textension(").Append(quantityName).AppendLine(")")
			.AppendLine("\t{");
		AppendFactory(extensions, quantityName, unitName, -siBasePrefixExponent);
		foreach (KeyValuePair<int, SiPrefix> prefix in prefixes)
		{
			AppendFactory(extensions, quantityName, prefix.Value.Name + unitName, prefix.Key - siBasePrefixExponent);
		}

		string variableName = char.ToLowerInvariant(quantityName[0]) + quantityName[1..];
		extensions.AppendLine("\t}").AppendLine()
			.Append("\textension(").Append(quantityName).Append(' ').Append(variableName).AppendLine(")")
			.AppendLine("\t{");
		AppendAccessor(extensions, variableName, unitName, -siBasePrefixExponent);
		foreach (KeyValuePair<int, SiPrefix> prefix in prefixes)
		{
			AppendAccessor(extensions, variableName, prefix.Value.Name + unitName, prefix.Key - siBasePrefixExponent);
		}

		extensions.AppendLine("\t}").AppendLine();
	}

	private static void AppendFactory(StringBuilder source, string quantityName, string unitName, int exponent)
	{
		source.Append("\t\tpublic static ").Append(quantityName).Append(" From").Append(unitName)
			.Append("(double value) => ").Append(quantityName).Append(".FromSiBaseUnit(value");
		if (exponent != 0)
		{
			source.Append(" * 1e").Append(exponent.ToString(CultureInfo.InvariantCulture));
		}

		source.AppendLine(");");
	}

	private static void AppendAccessor(StringBuilder source, string variableName, string unitName, int exponent)
	{
		source.Append("\t\tpublic double As").Append(unitName).Append("() => ").Append(variableName).Append(".AsSiBaseUnit()");
		if (exponent != 0)
		{
			source.Append(" / 1e").Append(exponent.ToString(CultureInfo.InvariantCulture));
		}

		source.AppendLine(";");
	}

	private static Type[] GetExponentTypes(Dimension dimension) =>
	[
		TypeSystemNumberCodec.CreateType(dimension.Length),
		TypeSystemNumberCodec.CreateType(dimension.Mass),
		TypeSystemNumberCodec.CreateType(dimension.Time),
		TypeSystemNumberCodec.CreateType(dimension.ElectricCurrent),
		TypeSystemNumberCodec.CreateType(dimension.Temperature),
		TypeSystemNumberCodec.CreateType(dimension.AmountOfSubstance),
		TypeSystemNumberCodec.CreateType(dimension.LuminousIntensity)
	];

	private static string FormatType(Type type)
	{
		string name = $"global::{type.Namespace}.{type.Name.Split('`')[0]}";
		return type.IsConstructedGenericType ? $"{name}<{string.Join(", ", type.GetGenericArguments().Select(FormatType))}>" : name;
	}
}
