using DimensionalQuantities.Roslyn.Discovery;

namespace DimensionalQuantities.Roslyn.Generators;

internal static class EnglishExponentAliasEmitter
{
	public static string Emit(IEnumerable<EnglishExponentAlias> aliases)
	{
		string declarations = string.Join("\n", aliases.GroupBy(alias => alias.Name, StringComparer.Ordinal)
			.OrderBy(group => group.Key, StringComparer.Ordinal)
			.Select(group => $"global using {group.Key} = {group.First().EncodedTypeName};"));
		return $"// <auto-generated />\n{declarations}\n";
	}
}
